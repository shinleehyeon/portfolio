export function FileTypeIcon({ name }: { name: string }) {
  const lower = name.toLowerCase();
  if (lower === "package.json") return <NpmIcon />;
  if (lower === "dockerfile" || lower.startsWith("docker-compose")) return <DockerIcon />;
  if (lower === "requirements.txt" || lower.endsWith(".py")) return <PythonIcon />;
  if (lower.endsWith(".tsx") || lower.endsWith(".jsx")) return <ReactIcon />;
  if (lower.endsWith(".ts") || lower.endsWith(".mts") || lower.endsWith(".cts")) return <TypescriptIcon />;
  if (lower.endsWith(".prisma")) return <PrismaIcon />;
  if (lower.endsWith(".tf")) return <TerraformIcon />;
  if (lower === "pom.xml" || lower.endsWith(".java")) return <JavaIcon />;
  if (lower.endsWith(".xml")) return <XmlIcon />;
  if (lower.endsWith(".yml") || lower.endsWith(".yaml")) return <YamlIcon />;
  if (lower.endsWith(".json")) return <JsonIcon />;
  if (lower.endsWith(".md")) return <MarkdownIcon />;
  if (lower.includes(".env") || lower.endsWith(".sh")) return <EnvIcon />;
  return <DocumentIcon />;
}
